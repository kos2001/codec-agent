"""Waveforms for any testbench run: VCD capture + extraction for the viewer.

Adapted from hls-rtl api/waveform.py. Two differences:

* **No testbench changes.** A separate root module `wave_dump` is compiled next to the
  testbench (`iverilog -s <tb> -s wave_dump`) and calls $dumpvars on the testbench
  hierarchy. The same capture works for the gate's testbench and for testbenches
  generated by Hermes.
* **A window, not the whole run.** A 65536-sample sweep would be tens of MB. The run is
  simulated once without tracing; if it failed, the window is centred on the first
  `ERROR ... t=<time>`; otherwise it covers reset plus the first cycles. Then it is
  re-simulated with tracing limited to that window.

Usage:
  python pipeline/waves.py --test L1_ulaw_enc                   # gate TB, committed RTL
  python pipeline/waves.py --test L1_ulaw_enc --rtl-dir <cand>  # gate TB, candidate RTL
  python pipeline/waves.py --tb <tb.sv> --module g711_ulaw_enc  # any testbench
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional, Tuple

sys.path.insert(0, str(Path(__file__).parent))
import gate  # noqa: E402

WAVES = gate.ROOT / "build" / "waves"
TB_DIR = gate.TB_DIR
CLK_PERIOD_NS = 10          # tb_g711 and the generated-TB contract both use #5 half periods
SIM_TIMEOUT = 300


def _tests() -> Dict[str, dict]:
    out = {}
    for line in (TB_DIR / "vectors" / "tests.txt").read_text().splitlines():
        if line.strip():
            name, mode, n, bp, stem = line.split()
            out[name] = {"mode": int(mode), "n": int(n), "bp": int(bp), "stem": stem}
    return out


def list_tests() -> List[dict]:
    return [{"name": k, **v} for k, v in _tests().items()]


def _dump_module(top: str, vcd: Path, start_cycle: int, cycles: int) -> str:
    """Root module that traces `top` for `cycles` clock edges after `start_cycle` edges.
    Counted on the testbench's own `clk`, so the window is independent of its
    `timescale and clock period (generated testbenches often declare neither)."""
    return f"""module wave_dump;
  initial begin
    $dumpfile("{vcd}");
    $dumpvars(0, {top});
    $dumpoff;
    repeat ({start_cycle}) @(posedge {top}.clk);
    $dumpon;
    repeat ({cycles}) @(posedge {top}.clk);
    $dumpoff;
  end
endmodule
"""


def _compile_and_run(sources: List[str], tops: List[str], params: List[str], work: Path) -> Tuple[bool, str]:
    work.mkdir(parents=True, exist_ok=True)
    vvp = work / "sim.vvp"
    cmd = ["iverilog", "-g2012", "-o", str(vvp)] + sum((["-s", t] for t in tops), []) + params + sources
    c = subprocess.run(cmd, capture_output=True, text=True, timeout=SIM_TIMEOUT)
    if c.returncode != 0:
        return False, "COMPILE ERROR\n" + c.stderr[-2000:]
    try:
        r = subprocess.run(["vvp", "-n", str(vvp)], capture_output=True, text=True, timeout=SIM_TIMEOUT, cwd=str(work))
        return True, r.stdout + r.stderr
    except subprocess.TimeoutExpired:
        return True, f"TIMEOUT after {SIM_TIMEOUT}s"


def capture(*, name: str, tb_sources: List[str], top: str, params: List[str], work: Path,
            cycles: int = 200, around_error: bool = True) -> dict:
    """Run once untraced to find the window, then again traced inside it."""
    t0 = time.time()
    ok, log = _compile_and_run(tb_sources, [top], params, work / "probe")
    if not ok:
        return {"available": False, "error": log}
    result = re.search(r"^RESULT (PASS|FAIL).*$", log, re.M)
    if result is None:
        # Nothing to centre on and nothing a waveform would explain: surface why.
        return {"available": False, "name": name, "result": None, "first_error": None,
                "error": "the testbench printed no RESULT line; simulator output:\n" + log[-1500:]}
    err = re.search(r"^ERROR.* t=(\d+)\s*$", log, re.M)   # trailing field; `got=` also contains "t="
    if err and around_error and top == "tb_g711":
        # tb_g711: `timescale 1ns/1ps, 10 ns clock; %t prints in ps.
        err_cycle = int(err.group(1)) // (CLK_PERIOD_NS * 1000)
        start_cycle = max(0, err_cycle - cycles // 2)
        reason = f"centred on first error (clock edge {err_cycle})"
    else:
        start_cycle = 0
        reason = "reset and first cycles" + ("; this testbench prints no error time" if err else "")
    WAVES.mkdir(parents=True, exist_ok=True)
    vcd = WAVES / f"{name}.vcd"
    dump = work / "wave_dump.sv"
    dump.write_text(_dump_module(top, vcd, start_cycle, cycles))
    ok, log2 = _compile_and_run(tb_sources + [str(dump)], [top, "wave_dump"], params, work / "trace")
    meta = {"name": name, "result": result.group(0) if result else None,
            "first_error": re.search(r"^ERROR.*$", log, re.M).group(0) if err else None,
            "window": {"start_cycle": start_cycle, "cycles": cycles, "reason": reason},
            "vcd": str(vcd.relative_to(gate.ROOT)), "elapsed_s": round(time.time() - t0, 1)}
    (WAVES / f"{name}.json").write_text(json.dumps(meta, indent=2))
    return {"available": vcd.exists(), **meta, "size_bytes": vcd.stat().st_size if vcd.exists() else 0}


def capture_gate_test(test: str, rtl_dir: Path = gate.BASELINE_RTL, *, cycles: int = 200, name: str = "") -> dict:
    t = _tests().get(test)
    if t is None:
        return {"available": False, "error": f"unknown test {test}"}
    vec = TB_DIR / "vectors"
    params = ["-P", f"tb_g711.MODE={t['mode']}", "-P", f"tb_g711.N={t['n']}", "-P", f"tb_g711.BP={t['bp']}",
              "-P", f'tb_g711.STIM="{vec / (t["stem"] + ".stim")}"', "-P", f'tb_g711.EXP="{vec / (t["stem"] + ".exp")}"']
    srcs = [str(TB_DIR / "tb_g711.sv")] + [str(rtl_dir / f"{m}.sv") for m in gate.MODULES]
    name = name or (f"{test}-baseline" if Path(rtl_dir).resolve() == gate.BASELINE_RTL.resolve()
                    else f"{test}-{Path(rtl_dir).parent.name}-{Path(rtl_dir).name}")
    return capture(name=name, tb_sources=srcs, top="tb_g711", params=params,
                   work=gate.ROOT / "build" / "waves-work" / name, cycles=cycles)


def capture_testbench(tb: Path, module: str, rtl_file: Optional[Path] = None, *, cycles: int = 200, name: str = "") -> dict:
    rtl_file = rtl_file or gate.BASELINE_RTL / f"{module}.sv"
    name = name or f"tb-{module}-{tb.parent.parent.name}-{tb.parent.name}"
    return capture(name=name, tb_sources=[str(tb), str(rtl_file)], top=f"tb_{module}", params=[],
                   work=gate.ROOT / "build" / "waves-work" / name, cycles=cycles)


def list_captures() -> List[dict]:
    if not WAVES.exists():
        return []
    out = []
    for j in sorted(WAVES.glob("*.json"), key=lambda p: p.stat().st_mtime, reverse=True):
        m = json.loads(j.read_text())
        v = gate.ROOT / m["vcd"]
        out.append({**m, "available": v.exists(), "size_bytes": v.stat().st_size if v.exists() else 0})
    return out


# ------------------------------------------------------------------ extraction ---

_VAR_RE = re.compile(r"\$var\s+(\w+)\s+(\d+)\s+(\S+)\s+([^\s$]+)(?:\s+\[[^\]]*\])?\s*\$end")
_SCOPE_RE = re.compile(r"\$scope\s+\w+\s+(\S+)\s+\$end")
_TIMESCALE_RE = re.compile(r"\$timescale\s+(\d+)\s*(\w+)\s*\$end")
_TS_UNITS = {"s": 1e0, "ms": 1e-3, "us": 1e-6, "ns": 1e-9, "ps": 1e-12, "fs": 1e-15}
PREFERRED_ORDER = ("clk", "rst_n", "in_valid", "in_ready", "in_pcm", "in_code", "in_data",
                   "out_valid", "out_ready", "out_code", "out_pcm", "out_data")


@dataclass
class Signal:
    name: str
    width: int
    kind: str
    scope: str
    transitions: List[Tuple[int, str]] = field(default_factory=list)


def _unit_label(seconds: float) -> str:
    for label, mult in (("s", 1e0), ("ms", 1e-3), ("us", 1e-6), ("ns", 1e-9), ("ps", 1e-12), ("fs", 1e-15)):
        if abs(seconds - mult) < mult * 0.01:
            return label
    return "ps"


def extract(name: str, *, scope: Optional[str] = None, max_transitions: int = 40000) -> dict:
    if not re.fullmatch(r"[\w.-]+", name):
        return {"available": False, "error": "bad capture name"}
    vcd = WAVES / f"{name}.vcd"
    if not vcd.exists():
        return {"available": False, "error": f"no capture {name}"}
    meta_p = WAVES / f"{name}.json"
    meta = json.loads(meta_p.read_text()) if meta_p.exists() else {}
    ids: Dict[str, Signal] = {}
    stack: List[str] = []
    counts: Dict[str, int] = {}
    ts = 1e-12
    with vcd.open("r", errors="replace") as fh:
        for line in fh:
            s = line.strip()
            if s.startswith("$timescale"):
                m = _TIMESCALE_RE.search(s)
                if m:
                    ts = int(m.group(1)) * _TS_UNITS.get(m.group(2), 1e-12)
                elif not s.endswith("$end"):
                    nxt = next(fh).strip()
                    m = re.match(r"(\d+)\s*(\w+)", nxt)
                    if m:
                        ts = int(m.group(1)) * _TS_UNITS.get(m.group(2), 1e-12)
            elif s.startswith("$scope"):
                m = _SCOPE_RE.search(s)
                stack.append(m.group(1) if m else "?")
            elif s.startswith("$upscope"):
                stack and stack.pop()
            elif s.startswith("$var"):
                m = _VAR_RE.search(s)
                if m:
                    path = ".".join(stack)
                    counts[path] = counts.get(path, 0) + 1
                    ids.setdefault(f"{path}|{m.group(3)}", Signal(m.group(4), int(m.group(2)), m.group(1), path))
            elif s.startswith("$enddefinitions"):
                break
        dut_scopes = [p for p in counts if re.search(r"\.(dut|enc|dec)$", p)]
        chosen = scope if scope in counts else (dut_scopes[0] if dut_scopes else max(counts, key=counts.get))
        wanted = {k.split("|", 1)[1]: v for k, v in ids.items() if v.scope == chosen and v.width <= 64}
        t, total, truncated, first_t, last_t = 0, 0, False, None, 0
        for line in fh:
            s = line.strip()
            if not s:
                continue
            c = s[0]
            if c == "#":
                t = int(s[1:]) if s[1:].isdigit() else t
                first_t = t if first_t is None else first_t
                last_t = t
                continue
            if c in "01xXzZ":
                vid, val = s[1:], c.lower()
            elif c in "bB":
                val, _, vid = s[1:].partition(" ")
                val, vid = val.lower(), vid.strip()
            else:
                continue
            sig = wanted.get(vid)
            if sig is None or (sig.transitions and sig.transitions[-1][1] == val):
                continue
            sig.transitions.append((t, val))
            total += 1
            if total >= max_transitions:
                truncated = True
                break

    # $dumpoff writes every signal as x at the moment tracing stops; that is an artefact
    # of the window, not X-propagation in the design.
    for sg in wanted.values():
        while sg.transitions and sg.transitions[-1][0] == last_t and re.fullmatch(r"[xz]+", sg.transitions[-1][1]) \
                and len(sg.transitions) > 1:
            sg.transitions.pop()

    def order(sg: Signal):
        return (PREFERRED_ORDER.index(sg.name), "") if sg.name in PREFERRED_ORDER else (len(PREFERRED_ORDER), sg.name)
    sigs = sorted(wanted.values(), key=order)
    return {"available": True, "name": name, "meta": meta, "scope": chosen,
            "scopes": [{"name": k, "signals": v} for k, v in sorted(counts.items())],
            "timescale_seconds": ts, "time_unit": _unit_label(ts),
            "start": first_t or 0, "end": last_t, "truncated": truncated, "transition_count": total,
            "parameters": [],
            "signals": [{"name": s.name, "width": s.width, "kind": s.kind, "scope": s.scope,
                         "transitions": [[a, b] for a, b in s.transitions]} for s in sigs]}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--test")
    ap.add_argument("--rtl-dir", type=Path, default=gate.BASELINE_RTL)
    ap.add_argument("--tb", type=Path)
    ap.add_argument("--module", choices=gate.MODULES)
    ap.add_argument("--cycles", type=int, default=200)
    a = ap.parse_args()
    if a.test:
        r = capture_gate_test(a.test, a.rtl_dir.resolve(), cycles=a.cycles)
    elif a.tb and a.module:
        r = capture_testbench(a.tb.resolve(), a.module, cycles=a.cycles)
    else:
        ap.error("--test, or --tb with --module")
    print(json.dumps(r, indent=2))
    return 0 if r.get("available") else 1


if __name__ == "__main__":
    sys.exit(main())
