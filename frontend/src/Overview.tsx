import type { Health, MutationRun, Proof, TestRun, GenerateRunSummary } from './types'
import { useT } from './i18n'

/**
 * Overview — what this workbench is FOR, then the live evidence for it.
 * Adapted from hls-rtl: the thesis first, then a proof chain whose rungs are
 * coloured by the latest real results rather than asserted.
 */

interface Props {
  health: Health | null
  gate: Proof | null
  tests: TestRun | null
  mutation: MutationRun | null
  runs: GenerateRunSummary[]
  onGo: (view: string) => void
}

type RungStatus = 'oracle' | 'pass' | 'fail' | 'skip'

export function Overview({ health, gate, tests, mutation, runs, onGo }: Props) {
  const t = useT()
  const stlCase = tests?.cases.filter((c) => c.file === 'test_golden') ?? []
  const pdfCase = tests?.cases.filter((c) => c.file === 'test_spec_tables') ?? []
  const status = (cs: { status: string }[]): RungStatus =>
    !cs.length ? 'skip' : cs.some((c) => c.status === 'fail') ? 'fail'
      : cs.every((c) => c.status === 'skip') ? 'skip' : 'pass'
  const proven = runs.filter((r) => r.outcome === 'PROVEN').length

  const rungs: { id: string; label: string; role: string; status: RungStatus; detail: string }[] = [
    { id: 'pdf', label: 'G.711 PDF', role: 'Tables 1a/1b/2a/2b', status: status(pdfCase),
      detail: pdfCase.length ? `${pdfCase.filter((c) => c.status === 'pass').length}/${pdfCase.length} table checks` : 'run L0 tests' },
    { id: 'stl', label: 'ITU-T STL', role: 'G.191 reference C · official vectors', status: 'oracle',
      detail: health?.stl_built ? 'built — 65536-sample sweep' : 'not built: missing evidence' },
    { id: 'model', label: 'spec_model', role: 'Python · from the table formulas', status: status(stlCase),
      detail: stlCase.length ? `${stlCase.filter((c) => c.status === 'pass').length}/${stlCase.length} vs STL / anchors` : 'run L0 tests' },
    { id: 'rtl', label: 'RTL', role: 'SystemVerilog · 4 modules', status: !gate ? 'skip' : gate.verdict === 'PROVEN' ? 'pass' : gate.verdict === 'REJECTED' ? 'fail' : 'skip',
      detail: gate ? `gate ${gate.verdict}` : 'no gate run' },
  ]

  const caps: { n: string; title: string; gap: string; view?: string }[] = [
    { n: '1', title: 'Sign-off gate', gap: 'lint → synth → 4-state sim → unbounded formal; a skip is never a pass', view: 'signoff' },
    { n: '2', title: 'Independent oracles', gap: 'STL, a table-formula model and the PDF tables agree before RTL is judged', view: 'spec' },
    { n: '3', title: 'Mutation coverage', gap: 'proves the gate would notice a wrong design', view: 'mutation' },
    { n: '4', title: 'Hermes generation loop', gap: 'the model proposes, the gate decides, evidence drives the repair', view: 'generate' },
    { n: '5', title: 'Traceability', gap: 'every REQ cites a G.711 clause/table or is marked DESIGN', view: 'spec' },
  ]

  return (
    <div className="view-scroll">
      <section className="thesis">
        <h1 className="thesis-claim">
          {t('An agent can write plausible RTL. It cannot tell you whether the RTL is right.')}
        </h1>
        <p className="thesis-body">
          codec-agent turns a codec standard into RTL and treats the RTL as a <b>claim</b>, not a
          deliverable. A candidate — hand-written or generated by the Hermes agent — is accepted
          only when a tool-driven gate with no model in the verdict says <b>PROVEN</b>.
        </p>
        <p className="thesis-claim-2">
          Pilot: ITU-T G.711 A-law / μ-law, encoder and decoder. Every 16-bit input and every code
          is compared against ITU-T STL, and the datapath is proven against the table formulas on
          every reachable trace.
        </p>
      </section>

      <section className="panel">
        <div className="panel-head">
          <h2>{t('The proof chain')}</h2>
          <button className="tb-btn" onClick={() => onGo('signoff')}>{t('Open sign-off →')}</button>
        </div>
        <div className="rungs">
          {rungs.map((r, i) => (
            <div key={r.id} className="rung-wrap">
              <div className={`rung rung-${r.status}`}>
                <div className="rung-top">
                  <span className="rung-label">{r.label}</span>
                  <span className={`badge badge-${r.status === 'oracle' ? 'pass' : r.status}`}>{r.status}</span>
                </div>
                <div className="rung-role">{r.role}</div>
                <div className="rung-detail muted small">{r.detail}</div>
              </div>
              {i < rungs.length - 1 && <div className="rung-arrow">≡</div>}
            </div>
          ))}
        </div>
        <p className="panel-foot muted small">
          Round-trip tests are deliberately not part of this chain: the first μ-law model inverted
          the sign bit in both directions and still round-tripped 65536/65536.
        </p>
      </section>

      <section className="stat-strip">
        <Stat label="gate" value={gate?.verdict ?? '—'} ok={gate?.verdict === 'PROVEN'} />
        <Stat label="L0 tests" value={tests ? tests.summary.replace(/ in .*/, '') : '—'} ok={tests?.returncode === 0} />
        <Stat label="mutants caught" value={mutation ? `${mutation.caught}/${mutation.total - mutation.equivalent}` : '—'} ok={mutation?.survived === 0} />
        <Stat label="generated & PROVEN" value={runs.length ? `${proven}/${runs.length} runs` : '—'} ok={proven > 0} />
        <Stat label="hermes model" value={health?.hermes_model?.split('/').pop() ?? '—'} />
      </section>

      <section className="panel panel-caveat">
        <strong>{t('What this does not prove.')}</strong> Inputs exactly on a decision value
        (G.711 §3.6 leaves them to the implementation — the STL convention is a DESIGN choice),
        excluded clauses (§3.2 all-zero suppression, §3.5 transcoding), and timing, area or power
        on a real library. A skipped stage is missing evidence, not a pass.
      </section>

      <section className="panel">
        <div className="panel-head">
          <h2>{t('What the workbench adds')}</h2>
          <button className="tb-btn" onClick={() => onGo('generate')}>{t('Open generate →')}</button>
        </div>
        <div className="caps">
          {caps.map((c) => (
            <button key={c.n} className={`cap ${c.view ? 'cap-go' : ''}`} onClick={() => c.view && onGo(c.view)}>
              <span className="cap-n">{c.n}</span>
              <span className="cap-title">{c.title}</span>
              <span className="cap-gap muted small">{c.gap}</span>
            </button>
          ))}
        </div>
        <p className="panel-foot muted small">
          Verification approach adapted from hls-rtl. The generator is the Hermes profile
          <code>codecagent</code> ({health?.hermes.base_url ?? '…'}), tools disabled, one turn per attempt.
        </p>
      </section>
    </div>
  )
}

function Stat({ label, value, ok }: { label: string; value: string; ok?: boolean }) {
  return (
    <div className={`stat ${ok === undefined ? '' : ok ? 'stat-ok' : 'stat-fail'}`}>
      <div className="stat-value">{value}</div>
      <div className="stat-label">{label}</div>
    </div>
  )
}
